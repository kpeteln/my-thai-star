-- ============================================================
-- TABLE: booking
-- Description: Table reservations (host + group bookings)
-- Domain: Booking Management
--
-- CIRCULAR REFERENCE RESOLUTION:
--   booking.id_order → orders(id)   [host's order for this booking]
--   orders.id_booking → booking(id)  [the booking an order belongs to]
-- Strategy: Create booking without the id_order FK first,
--           then add it as a DEFERRABLE FK after orders is created.
-- ============================================================
CREATE TABLE booking (
    id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000 INCREMENT BY 1),
    modification_counter INTEGER      NOT NULL DEFAULT 0,
    id_user              BIGINT,
    name                 VARCHAR(255) NOT NULL,
    booking_token        VARCHAR(60),
    comment              VARCHAR(4000),
    email                VARCHAR(255) NOT NULL,
    booking_date         TIMESTAMP WITH TIME ZONE NOT NULL,
    expiration_date      TIMESTAMP WITH TIME ZONE,
    creation_date        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    canceled             BOOLEAN      NOT NULL DEFAULT FALSE,
    booking_type         INTEGER,
    id_table             BIGINT,
    id_order             BIGINT,   -- Resolved FK added below via ALTER TABLE
    assistants           INTEGER,

    CONSTRAINT pk_booking        PRIMARY KEY (id),
    CONSTRAINT uq_booking_token  UNIQUE (booking_token),
    CONSTRAINT fk_booking_user   FOREIGN KEY (id_user)
                                     REFERENCES "user" (id)
                                     ON DELETE SET NULL,
    CONSTRAINT fk_booking_table  FOREIGN KEY (id_table)
                                     REFERENCES restaurant_table (id)
                                     ON DELETE SET NULL,

    -- BR-004: assistants must be between 1 and 99 (@Min=1, @Digits(integer=2))
    CONSTRAINT chk_booking_assistants CHECK (
        assistants IS NULL OR (assistants >= 1 AND assistants <= 99)
    ),

    -- BR-001 / BR-002: token format validation
    --   Host  tokens: CB_YYYYMMDD_<32-char md5hex>
    --   Guest tokens: GB_YYYYMMDD_<32-char md5hex>
    CONSTRAINT chk_booking_token_format CHECK (
        booking_token IS NULL OR
        booking_token ~ '^(CB|GB)_[0-9]{8}_[0-9a-f]{32}$'
    ),

    -- BR-003: expiration must be before booking date (= bookingDate - 1 hour)
    CONSTRAINT chk_booking_expiration CHECK (
        expiration_date IS NULL OR expiration_date < booking_date
    ),

    -- booking_type: 0 = CommonBooking (CSR), 1 = GuestInviteBooking (GSR)
    CONSTRAINT chk_booking_type CHECK (booking_type IN (0, 1))
);

COMMENT ON TABLE  booking               IS 'Table reservation. booking_type=0: single-party; booking_type=1: group invite with InvitedGuest records';
COMMENT ON COLUMN booking.booking_token IS 'Unique access token (BR-001: CB_YYYYMMDD_<md5> for host). Immutable after creation';
COMMENT ON COLUMN booking.booking_date  IS 'UTC timestamp of the reserved slot (stored as Instant / TIMESTAMP WITH TIME ZONE)';
COMMENT ON COLUMN booking.expiration_date IS 'Auto-computed = booking_date − 1 hour (BR-003); guest must accept before this deadline';
