-- View: daily_ordered_dishes
-- Purpose: Aggregate dish demand per calendar day
CREATE OR REPLACE VIEW daily_ordered_dishes AS
SELECT
    ol.id_dish                  AS id_dish,
    DATE(b.booking_date)        AS booking_date,
    SUM(ol.amount)::INTEGER     AS amount
FROM order_line   ol
JOIN orders       o  ON ol.id_order  = o.id
JOIN booking      b  ON o.id_booking = b.id
GROUP BY ol.id_dish, DATE(b.booking_date)
ORDER BY booking_date, id_dish;

COMMENT ON VIEW daily_ordered_dishes IS 'Daily dish demand aggregation; join with date_info for temperature enrichment';

-- View: monthly_ordered_dishes
-- Purpose: Monthly demand with avg temperature (for seasonal ML features)
CREATE OR REPLACE VIEW monthly_ordered_dishes AS
SELECT
    ol.id_dish                                            AS id_dish,
    DATE_TRUNC('month', b.booking_date)::DATE             AS booking_date,
    ROUND(AVG(di.temperature)::NUMERIC, 1)::DOUBLE PRECISION AS temperature,
    SUM(ol.amount)::INTEGER                               AS amount
FROM order_line   ol
JOIN orders       o  ON ol.id_order  = o.id
JOIN booking      b  ON o.id_booking = b.id
JOIN date_info    di
    ON TO_CHAR(di."date", 'YYYY-MM') = TO_CHAR(b.booking_date AT TIME ZONE 'UTC', 'YYYY-MM')
GROUP BY ol.id_dish, DATE_TRUNC('month', b.booking_date)
ORDER BY booking_date, id_dish;

COMMENT ON VIEW monthly_ordered_dishes IS 'Monthly dish demand with average temperature; used by monthly ML forecasting models';

-- View: ordered_dishes_per_day
-- Purpose: Enriched daily report with dish + weather metadata (prediction service entity)
CREATE OR REPLACE VIEW ordered_dishes_per_day AS
SELECT
    (TO_CHAR(dod.booking_date, 'YYYYMMDD') || dod.id_dish::TEXT)::BIGINT AS id,
    d.modification_counter,
    di.temperature,
    di.designation,
    dod.id_dish,
    dod.booking_date,
    dod.amount
FROM daily_ordered_dishes dod
JOIN dish      d  ON dod.id_dish   = d.id
JOIN date_info di ON di."date"     = dod.booking_date;

COMMENT ON VIEW ordered_dishes_per_day IS 'Full daily order report with dish metadata and weather data; mapped by OrderedDishesPerDayEntity JPA view entity';

-- View: ordered_dishes_per_month
-- Purpose: Enriched monthly report with dish metadata (prediction service entity)
CREATE OR REPLACE VIEW ordered_dishes_per_month AS
SELECT
    (TO_CHAR(mod2.booking_date, 'YYYYMMDD') || mod2.id_dish::TEXT)::BIGINT AS id,
    d.modification_counter,
    mod2.id_dish,
    mod2.booking_date,
    mod2.temperature,
    mod2.amount
FROM monthly_ordered_dishes mod2
JOIN dish d ON mod2.id_dish = d.id;

COMMENT ON VIEW ordered_dishes_per_month IS 'Full monthly order report with dish metadata; mapped by OrderedDishesPerMonthEntity JPA view entity';

-- View: geo_booking
-- Purpose: Spatial join of orders → users → addresses for clustering/heatmap
CREATE OR REPLACE VIEW geo_booking AS
SELECT
    ol.id_dish,
    d.name      AS dish_name,
    b.booking_date,
    a.geocode,
    ol.amount
FROM booking    b
JOIN "user"     u  ON u.id         = b.id_user
JOIN addresses  a  ON u.id         = a.id_user
JOIN orders     o  ON o.id_booking = b.id
JOIN order_line ol ON o.id         = ol.id_order
JOIN dish       d  ON d.id         = ol.id_dish;

COMMENT ON VIEW geo_booking IS 'Spatial analytics view: orders + user geocodes; used by clustering / demand heatmap features';

-- ============================================================
-- TRIGGER: Auto-increment modification_counter on UPDATE
-- Emulates JPA @Version optimistic-locking (BR-012)
-- ============================================================
CREATE OR REPLACE FUNCTION trg_increment_modification_counter()
RETURNS TRIGGER AS $$
BEGIN
    NEW.modification_counter = OLD.modification_counter + 1;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION trg_increment_modification_counter() IS
    'Auto-increments modification_counter on every UPDATE row; mirrors JPA @Version optimistic-locking (BR-012)';

-- Apply modification_counter trigger to all versioned tables
DO $$
DECLARE
    tbl TEXT;
BEGIN
    FOREACH tbl IN ARRAY ARRAY[
        'user_role',
        'image',
        'category',
        'ingredient',
        '"user"',
        'dish',
        'dish_category',
        'dish_ingredient',
        'user_favourite',
        'restaurant_table',
        'booking',
        'invited_guest',
        'orders',
        'order_line',
        'order_dish_extra_ingredient',
        'binary_object',
        'prediction_all_forecast',
        'prediction_all_models'
    ] LOOP
        EXECUTE format(
            $fmt$
            CREATE TRIGGER trg_%s_mod_counter
            BEFORE UPDATE ON %s
            FOR EACH ROW
            EXECUTE FUNCTION trg_increment_modification_counter()
            $fmt$,
            replace(replace(tbl, '"', ''), '.', '_'),
            tbl
        );
    END LOOP;
END;
$$;

